"""Investigated items from Pydro Feature Reports in NOAA Descriptive Reports (CC0).

Newer H-survey DRs append Pydro-generated reports (AWOIS items, Dangers to Navigation, new
features). Each item section starts with a heading like ``1.2)  AWOIS 14921`` and carries a
survey position, least depth, the field team's Remarks, the Hydrographer Recommendations,
the S-57 object class and the reviewing office's Office Notes. The office is the final word:
when it does not concur, only its notes decide the outcome.

These are expert dispositions backed by side-scan and/or multibeam evidence, not physical
verification, unless a diver or ROV is mentioned. History Notes (old reports) are ignored.
"""

from __future__ import annotations

import csv
import re
from dataclasses import asdict, dataclass, fields
from pathlib import Path

HEAD = re.compile(r"^[ \t]*(\d+(?:\.\d+)+)\)[ \t]+(\S.*?)[ \t]*$", re.M)
MIN = "['’′�]"  # minute mark: ASCII, curly, prime, or lost in PDF extraction
COORD = (
    r"(\d{1,3})\D{1,3}?(\d{1,2})" + MIN + r"\s*(\d{1,2}(?:\.\d+)?)\S?\s*([NS]),?\s*"
    r"(\d{1,3})\D{1,3}?(\d{1,2})" + MIN + r"\s*(\d{1,2}(?:\.\d+)?)\S?\s*([EW])"
)
SURVEY_POS = re.compile(r"Survey Position:\s*" + COORD)
SEARCH_POS = re.compile(r"Search Position:\s*" + COORD)
LEAST_DEPTH = re.compile(r"Least Depth:\s*(?:\[None\]|(-?\d+(?:\.\d+)?)\s*m\b)")
S57_CLASS = re.compile(r"\((\$?[A-Z]{5,6})\)")
FOOTER = re.compile(
    r"^(?:H\d{5}[\s_].*|\d+ - .*|Page \d+|APPROVAL PAGE.*|Generated by Pydro.*|Feature Images.*)$"
)

REMARK_STOPS = (
    "Feature Correlation", "Hydrographer Recommendations", "S-57 Data", "Office Notes",
    "Cartographically", "Geo object",
)
RECOMMENDATION_STOPS = (
    "Cartographically", "S-57 Data", "Geo object", "Office Notes", "Feature Correlation",
)
OFFICE_STOPS = ("Hydrographer Recommendations", "S-57 Data", "Geo object", "Feature Correlation")

OVERRIDE = re.compile(r"\b(?:do|does|did) not concur\b|\bnon-?concur", re.I)
# "inadequate to disprove", "not considered as disproved": an object may well be there.
INCONCLUSIVE = re.compile(
    r"\b(?:inadequate|insufficient|unable|not able|cannot|could not) to disprove"
    r"|\bnot (?:be )?considered (?:as )?disproved|\bnot disproved\b|\bcannot be disprove[nd]\b"
    r"|\b(?:entire|full) (?:search )?(?:area|radius)\b[^.;]{0,30}?\bnot (?:fully )?"
    r"(?:covered|searched|conducted|completed)\b"
    r"|\bsearch (?:area|radius) (?:was )?(?:not (?:fully )?covered|incomplete)\b",
    re.I,
)
# Old reports quoted inside an item ("History ..."): not evidence from this survey.
HISTORY_BLOCK = re.compile(
    r"^\s*history\b.*?(?=\$?[A-Z]{5,6}/(?:invreq|remrks):|\Z)", re.I | re.S
)
SENTENCE = re.compile(r"(?<=[.;])\s+")
# Charted soundings (S-57 SOUNDG) are usually seabed relief. In hydrographic reports the word
# "feature" means anything charted, sand bars included, so it alone proves nothing.
SEABED_WORDS = re.compile(
    r"\bmigrat(?:ed|ing|ion)\b|\bsand ?(?:waves?|bars?)\b|\bbar has\b"
    r"|\b(?:seafloor|benthic|shoal|spoil) mounds?\b|\bnatural (?:seafloor )?shoal\b",
    re.I,
)
SPECIFIC_OBJECT_WORDS = re.compile(
    # "object detection" is a multibeam survey mode, not an object
    r"\b(?:rocks?|wrecks?|obstructions?|debris|contacts?|objects?(?! detection)|targets?"
    r"|piles?|pilings?)\b",
    re.I,
)
GENERIC_FEATURE = re.compile(r"\bfeatures?\b", re.I)
DISPROVED = re.compile(
    r"disprov|no evidence of|\bnot (?:been |be )?(?:found|seen|observed|located|detected|visible"
    r"|identified|present)\b|did not (?:see|find|detect|locate)\b"
    r"|could not (?:be )?(?:find|found|locate|located)"
    r"|\bnothing\b(?:\s+\w+){0,4}?\s+(?:was |were )?(?:found|seen|observed|detected)"
    r"|\bno (?:\w+ ){0,2}?(?:feature|contact|object|wreck|obstruction)s?\b(?:\s+\w+){0,4}?\s+"
    r"(?:was |were )?(?:found|seen|observed|detected)",
    re.I,
)
RECLASS = re.compile(
    r"\bnot an? (?:rock|wreck|obstruction|pile|object|feature)\b|\bsand ?waves?\b"
    r"|\bmigrat(?:ed|ing|ion)\b|\bsand ?bars?\b|\b(?:seafloor|benthic|shoal) mounds?\b",
    re.I,
)
# S-57 classes that are seabed relief, not discrete objects (MORFAC moorings are objects).
SEABED_CLASSES = frozenset({"SNDWAV", "SOUNDG", "DEPARE", "SBDARE", "DEPCNT"})
REAL = re.compile(
    r"verified|\bfound\b|\blocated\b|\bseen\b|\bobserved\b|evidence of|\bdeveloped\b"
    r"|\bis real\b|update least depth|least depth of|\bpart of\b|\bas surveyed\b"
    r"|\b(?:chart|add|insert)\b(?:\s+\w+){0,3}?\s+(?:rock|wreck|obstruction|pile|piling"
    r"|stakes?|cable|chain|pipe(?:line)?|buoy|debris|object)\b",
    re.I,
)
DELETE = re.compile(r"\b(?:delete|remove)\b", re.I)
RETAIN = re.compile(r"\bretain", re.I)
PHYSICAL = re.compile(r"\bdivers?\b|\bROV\b|dive team", re.I)
MBES = re.compile(r"MBES|multibeam|SWMB|\bODMB\b|object detection", re.I)
SSS = re.compile(r"\bSSS\b|side ?scan", re.I)

REAL_BY_DISPOSITION = {
    "verified": True,
    "disproved": False,
    "deleted": None,  # deletion without stated evidence is not proof of absence
    "reclassified_seabed": False,
    "inconclusive": None,
    "retained_unverified": None,
    "unknown": None,
}


@dataclass
class FeatureItem:
    survey_id: str
    item_no: str
    name: str
    item_kind: str  # awois | dton | feature
    lat: float | None
    lon: float | None
    least_depth_m: float | None
    s57_class: str | None
    disposition: str
    is_real_object: bool | None
    office_overrode: bool
    ground_truth: str  # physical_verification | multibeam_developed | expert_disposition
    mentions_sss: bool
    mentions_mbes: bool
    remarks: str
    recommendation: str
    office_notes: str
    page: int
    source: str = "feature_report"


def _clean(text: str) -> str:
    return " ".join(text.replace("[None]", " ").split())


def strip_history(text: str) -> str:
    """Remove quoted history (a leading 'History ...' block and sentences about the history)."""
    text = HISTORY_BLOCK.sub(" ", text)
    kept = [s for s in SENTENCE.split(text) if "histor" not in s.lower()]
    return _clean(" ".join(kept))


def _field(lines: list[str], label: str, stops: tuple[str, ...]) -> str:
    """Text after `label` (same line and following lines) up to a stop label or page footer."""
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith(label):
            out = [stripped[len(label) :].lstrip(":")]
            for nxt in lines[i + 1 :]:
                s = nxt.strip()
                if s.startswith(stops) or FOOTER.match(s):
                    break
                out.append(s)
            return _clean(" ".join(out))
    return ""


def _coord(m: re.Match) -> tuple[float, float]:
    g = m.groups()
    lat = float(g[0]) + float(g[1]) / 60 + float(g[2]) / 3600
    lon = float(g[4]) + float(g[5]) / 60 + float(g[6]) / 3600
    return (-lat if g[3] == "S" else lat), (-lon if g[7] == "W" else lon)


def classify_feature(
    remarks: str,
    recommendation: str,
    office_notes: str,
    *,
    s57_class: str | None,
    least_depth_m: float | None,
) -> tuple[str, bool | None, bool]:
    """Return (disposition, is_real_object, office_overrode).

    Fields are read in authority order: Office Notes, then Hydrographer Recommendations, then
    the field Remarks; the first field with decisive wording wins. Within a field the order is
    inconclusive > disproved > reclassified as seabed > verified. If the office does not
    concur, only its notes count. Weak signals (S-57 seabed class, measured least depth, a
    bare delete/retain) apply only when no field is decisive.
    """
    remarks, recommendation, office_notes = (
        strip_history(t) for t in (remarks, recommendation, office_notes)
    )
    overrode = bool(OVERRIDE.search(office_notes))
    texts = (office_notes,) if overrode else (office_notes, recommendation, remarks)
    disposition = None
    for text in texts:
        if INCONCLUSIVE.search(text):
            disposition = "inconclusive"
        elif DISPROVED.search(text):
            disposition = "disproved"
        elif RECLASS.search(text):
            disposition = "reclassified_seabed"
        elif REAL.search(text):
            disposition = "verified"
        if disposition:
            break
    joined = " ".join(texts)
    if s57_class == "SOUNDG" and disposition in (None, "verified"):
        if SEABED_WORDS.search(joined):
            disposition = "reclassified_seabed"
        elif SPECIFIC_OBJECT_WORDS.search(joined):
            disposition = "verified" if disposition == "verified" else "unknown"
        elif GENERIC_FEATURE.search(joined):
            disposition = "unknown"  # a "feature" charted as a depth: object or relief
        else:
            disposition = "reclassified_seabed"
    if disposition is None:
        if s57_class in SEABED_CLASSES:
            disposition = "reclassified_seabed"
        elif least_depth_m is not None:
            disposition = "verified"
        elif DELETE.search(joined):
            disposition = "deleted"
        elif RETAIN.search(joined):
            disposition = "retained_unverified"
        else:
            disposition = "unknown"
    if disposition == "verified" and s57_class in SEABED_CLASSES - {"SOUNDG"}:
        disposition = "reclassified_seabed"  # a real shoal is seabed relief, not an object
    return disposition, REAL_BY_DISPOSITION[disposition], overrode


def _item_kind(name: str, body: str) -> str:
    if "AWOIS" in name.upper():
        return "awois"
    if re.search(r"\bDTON\b|DANGER TO NAVIGATION", name + "\n" + body[:300], re.I):
        return "dton"
    if "AWOIS Item" in body:
        return "awois"
    return "feature"


def _parse_item(survey_id: str, item_no: str, name: str, body: str, page: int):
    pos = SURVEY_POS.search(body) or SEARCH_POS.search(body)
    if not pos:
        return None
    lat, lon = _coord(pos)
    depth_m = LEAST_DEPTH.search(body)
    least_depth = float(depth_m.group(1)) if depth_m and depth_m.group(1) else None
    lines = body.splitlines()
    remarks = strip_history(_field(lines, "Remarks", REMARK_STOPS))
    recommendation = _field(lines, "Hydrographer Recommendations", RECOMMENDATION_STOPS)
    office = _field(lines, "Office Notes", OFFICE_STOPS)
    s57_at = body.find("S-57 Data")
    cls = S57_CLASS.search(body, s57_at if s57_at >= 0 else 0) or S57_CLASS.search(body)
    s57 = cls.group(1) if cls else None
    disposition, is_real, overrode = classify_feature(
        remarks, recommendation, office, s57_class=s57, least_depth_m=least_depth
    )
    evidence = " ".join((remarks, recommendation, office))
    mbes = bool(MBES.search(evidence))
    if PHYSICAL.search(evidence):
        ground_truth = "physical_verification"
    elif mbes or least_depth is not None:
        ground_truth = "multibeam_developed"
    else:
        ground_truth = "expert_disposition"
    return FeatureItem(
        survey_id=survey_id,
        item_no=item_no,
        name=name,
        item_kind=_item_kind(name, body),
        lat=lat,
        lon=lon,
        least_depth_m=least_depth,
        s57_class=s57,
        disposition=disposition,
        is_real_object=is_real,
        office_overrode=overrode,
        ground_truth=ground_truth,
        mentions_sss=bool(SSS.search(evidence)),
        mentions_mbes=mbes,
        remarks=remarks,
        recommendation=recommendation,
        office_notes=office,
        page=page,
    )


def parse_feature_items(pages: list[str], survey_id: str) -> list[FeatureItem]:
    """All investigated items with a position; repeated reports of one item are merged."""
    text, starts = "", []
    for page in pages:
        starts.append(len(text))
        text += page + "\n"
    heads = list(HEAD.finditer(text))
    items: dict[tuple, FeatureItem] = {}
    for i, h in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        page_no = sum(1 for s in starts if s <= h.start())
        item = _parse_item(survey_id, h.group(1), h.group(2), text[h.end() : end], page_no)
        if item is None:
            continue
        key = (round(item.lat, 5), round(item.lon, 5), item.least_depth_m)
        old = items.get(key)
        if old is None or (
            old.is_real_object is None and item.is_real_object is not None
        ):
            items[key] = item
    return list(items.values())


def write_features_csv(rows: list[FeatureItem], path: str | Path) -> Path:
    path = Path(path)
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=[f.name for f in fields(FeatureItem)])
        writer.writeheader()
        for row in rows:
            writer.writerow(asdict(row))
    return path
